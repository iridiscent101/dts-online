    public function run(): void
    {
        $timestamp = now();
        $schools = collect(self::SCHOOLS)
            ->map(fn (array $school): array => [
                'source_unit_id' => $school[0],
                'name' => $school[1],
                'created_at' => $timestamp,
                'updated_at' => $timestamp,
            ])
            ->all();

        foreach (array_chunk($schools, 100) as $chunk) {
            School::query()->upsert($chunk, ['source_unit_id'], ['name', 'updated_at']);
        }
    }
